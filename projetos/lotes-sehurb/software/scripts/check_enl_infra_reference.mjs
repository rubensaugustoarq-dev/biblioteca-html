import {build} from '../apps/web/node_modules/esbuild/lib/main.js';
import assert from 'node:assert/strict';
await build({entryPoints:['apps/web/src/features/enl/infraReference.ts'],bundle:true,platform:'node',format:'esm',outfile:'.runtime/enl-infra-reference-check.mjs'});
const {InfraReference,infraReferenceFeatures}=await import('../.runtime/enl-infra-reference-check.mjs');
const square={type:'Polygon',coordinates:[[[10,20],[20,20],[20,30],[10,30],[10,20]],[[12,22],[12,24],[14,24],[14,22],[12,22]]]};
const multi={type:'MultiPolygon',coordinates:[square.coordinates]};
const axis={type:'LineString',coordinates:[[10,20],[20,30]]};
const walk={role:'sidewalk',material:'concrete',geometry:multi},pavement={role:'pavement',material:'brick',geometry:square};
const doc={infra:[{id:'road',name:'Via 1',kind:'road',derived:{axisGeometry:axis,regions:[pavement,walk]}},{id:'surface',name:'Pátio',kind:'surface',derived:{regions:[pavement]}}],infraMetrics:{regions:[walk,pavement]}};
const original=JSON.stringify(doc);
assert.equal(infraReferenceFeatures(doc,{}).length,0);
assert.equal(infraReferenceFeatures(doc,{roads:true}).length,3);
assert.equal(infraReferenceFeatures(doc,{surfaces:true}).length,1);
assert.equal(infraReferenceFeatures(doc,{roads:true,surfaces:true}).length,3,'both use canonical final regions, not overlapping individual polygons');
const reference=new InfraReference(true);reference.update(doc,{roads:true,surfaces:true},p=>[p[1]-20,10-p[0]]);
const features=reference.source.getFeatures();assert.equal(features.length,3);
const transformed=features.find(f=>f.getGeometry().getType()==='Polygon').getGeometry().getCoordinates();
assert.deepEqual(transformed[0][0],[0,0]);assert.deepEqual(transformed[1][0],[2,-2],'hole follows technical view rotation');
assert.deepEqual(features.find(f=>f.get('role')==='axis').getGeometry().getCoordinates(),[[0,0],[10,-10]]);
reference.update(doc,{surfaces:true},p=>p);assert.equal(reference.source.getFeatures().length,1);
reference.update(doc,{},p=>p);assert.equal(reference.source.getFeatures().length,0,'disabling clears references and their snapping geometry');
assert.equal(JSON.stringify(doc),original,'visibility never mutates document or ENL metrics');
console.log('ENL: vias/calçadas e pavimentações independentes, união confirmada, rotação, vazios e documento preservado aprovados.');
