import {build} from '../apps/web/node_modules/esbuild/lib/main.js';
import assert from 'node:assert/strict';
import Feature from '../apps/web/node_modules/ol/Feature.js';
import Polygon from '../apps/web/node_modules/ol/geom/Polygon.js';
import {get as projection} from '../apps/web/node_modules/ol/proj.js';
await build({entryPoints:['apps/web/src/dimensionSnap.ts'],bundle:true,platform:'node',format:'esm',outfile:'.runtime/dimension-snap-check.mjs'});
const {dimensionSnap,dimensionSnapFeatures}=await import('../.runtime/dimension-snap-check.mjs');
const feature=(ring,use)=>{const f=new Feature(new Polygon([ring]));f.set('use',use);return f;};
const base=feature([[0,0],[100,0],[100,100],[0,100],[0,0]]);
const lot=feature([[10,10],[20,10],[20,30],[10,30],[10,10]],'lot');
const hidden=feature([[40,40],[50,40],[50,60],[40,60],[40,40]],'lot');
const layer=(values,visible=true)=>({getVisible:()=>visible,getSource:()=>({getFeatures:()=>values})});
const map={getLayers:()=>({getArray:()=>[layer([base]),layer([lot]),layer([hidden],false)]}),getView:()=>({getProjection:()=>projection('EPSG:3857'),getResolution:()=>.1}),getPixelFromCoordinate:p=>p.map(v=>v*10)};
const selected=dimensionSnapFeatures([base],map);assert.equal(selected.length,2);assert.ok(selected.includes(lot));assert.ok(!selected.includes(hidden));
const snap=dimensionSnap([base],map);snap.setMap(map);
const at=p=>snap.snapTo(map.getPixelFromCoordinate(p),p,map);
assert.deepEqual(at([10.3,10.2]).vertex,[10,10],'Lot vertex captured exactly');
assert.deepEqual(at([15,9.8]).vertex,[15,10],'Middle of lot side captured exactly');
assert.deepEqual(at([.2,.3]).vertex,[0,0],'Gleba capture preserved');
assert.equal(at([45,39.8]),null,'Hidden lots are not snap targets');
assert.deepEqual(lot.getGeometry().getCoordinates()[0][0],[10,10]);
snap.setMap(null);snap.dispose();console.log('Snap da cota: vértices e linhas dos lotes visíveis, contorno da gleba e camadas ocultas passaram.');
